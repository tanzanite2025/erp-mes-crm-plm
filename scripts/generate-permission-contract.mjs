import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)))
const sourceFile = join(repoRoot, 'server', 'authz', 'permissions.go')
const routeContractFile = join(repoRoot, 'server', 'authz', 'route_permission_contract.gen.go')
const outputFile = join(repoRoot, 'src', 'features', 'authz', 'data', 'permission-contract.gen.ts')

const MANAGED_PERMISSION_PREFIX = /^(menu_|action_|user_|perm_)/

function parseConstEntries(goSource) {
  const entries = []
  const constBlockPattern = /const\s*\(([\s\S]*?)\)/g

  for (const blockMatch of goSource.matchAll(constBlockPattern)) {
    const blockBody = blockMatch[1]
    const linePattern = /^\s*([A-Za-z0-9_]+)\s*=\s*"([^"]+)"/gm

    for (const lineMatch of blockBody.matchAll(linePattern)) {
      const [, name, value] = lineMatch
      entries.push({ name, value })
    }
  }

  return entries
}

function parseStringSliceConstantNames(goSource, variableName) {
  const fallbackMatch = goSource.match(new RegExp(`var\\s+${variableName}\\s*=\\s*\\[\\]string\\s*\\{([\\s\\S]*?)\\}`, 'm'))
  if (!fallbackMatch) {
    return null
  }

  return fallbackMatch[1]
    .split('\n')
    .map((line) => line.replace(/\/\/.*$/, '').trim())
    .filter(Boolean)
    .map((line) => line.replace(/,$/, '').trim())
    .filter(Boolean)
}

function parseAdminFallbackConstantNames(goSource) {
  const staticAdminFallback = parseStringSliceConstantNames(goSource, 'AdminFallbackPermissions')
  if (staticAdminFallback) {
    return staticAdminFallback
  }

  const baseAdminFallback = parseStringSliceConstantNames(goSource, 'baseAdminFallbackPermissions')
  if (baseAdminFallback) {
    return baseAdminFallback
  }

  throw new Error('[permission-contract] Admin fallback permission block not found in source file.')
}

function usesGeneratedRoutePermissionsInAdminFallback(goSource) {
  return /var\s+AdminFallbackPermissions\s*=\s*buildAdminFallbackPermissions\s*\(\s*\)/m.test(goSource)
}

function parseKnownRoutePermissionIds(routeContractSource) {
  return Array.from(routeContractSource.matchAll(/"([^"]+)"\s*:\s*\{\}/g)).map((match) => match[1])
}

function dedupe(ids) {
  const seen = new Set()
  const result = []

  ids.forEach((id) => {
    const normalized = id.trim().toLowerCase()
    if (!normalized || seen.has(normalized)) return
    seen.add(normalized)
    result.push(normalized)
  })

  return result
}

const goSource = readFileSync(sourceFile, 'utf8')
const routeContractSource = readFileSync(routeContractFile, 'utf8')
const constEntries = parseConstEntries(goSource)
const byConstName = new Map(constEntries.map((entry) => [entry.name, entry.value]))

const backendPermissionIds = dedupe(
  constEntries
    .map((entry) => entry.value)
    .filter((value) => MANAGED_PERMISSION_PREFIX.test(value)),
)

if (backendPermissionIds.length === 0) {
  throw new Error('[permission-contract] No managed permission IDs were parsed from backend source.')
}

const adminFallbackConstNames = parseAdminFallbackConstantNames(goSource)
const generatedRoutePermissionIds = usesGeneratedRoutePermissionsInAdminFallback(goSource)
  ? parseKnownRoutePermissionIds(routeContractSource)
  : []
const adminFallbackPermissionIds = dedupe(
  [
    ...adminFallbackConstNames.map((constName) => {
      const mapped = byConstName.get(constName)
      if (!mapped) {
        throw new Error(`[permission-contract] Unknown constant in admin fallback permissions: ${constName}`)
      }
      return mapped
    }),
    ...generatedRoutePermissionIds,
  ],
)

const output = `// This file is auto-generated by scripts/generate-permission-contract.mjs
// Source of truth: server/authz/permissions.go
// Do not edit manually.

export const BACKEND_PERMISSION_CONTRACT_IDS = ${JSON.stringify(backendPermissionIds, null, 2)} as const

export const BACKEND_ADMIN_FALLBACK_PERMISSION_IDS = ${JSON.stringify(adminFallbackPermissionIds, null, 2)} as const

const BACKEND_PERMISSION_CONTRACT_SET = new Set(BACKEND_PERMISSION_CONTRACT_IDS)
const BACKEND_MANAGED_PERMISSION_PREFIX = /^(menu_|action_|user_|perm_)/

function normalizePermissionId(permissionId: string): string {
  return permissionId.trim().toLowerCase()
}

/**
 * Assert frontend managed permission IDs stay aligned with backend source of truth.
 *
 * Rules:
 * 1. Backend-managed IDs must all exist in frontend permission registry.
 * 2. Frontend IDs that match managed prefixes cannot drift out of backend contract.
 */
export function assertBackendPermissionContract(permissionIds: string[]): void {
  const normalizedFrontendIds = new Set(
    permissionIds.map((permissionId) => normalizePermissionId(permissionId)).filter(Boolean),
  )

  const missingFromFrontend = BACKEND_PERMISSION_CONTRACT_IDS.filter(
    (permissionId) => !normalizedFrontendIds.has(permissionId),
  )

  const unexpectedManagedIds = Array.from(normalizedFrontendIds).filter(
    (permissionId) =>
      BACKEND_MANAGED_PERMISSION_PREFIX.test(permissionId) &&
      !BACKEND_PERMISSION_CONTRACT_SET.has(permissionId as (typeof BACKEND_PERMISSION_CONTRACT_IDS)[number]),
  )

  if (missingFromFrontend.length === 0 && unexpectedManagedIds.length === 0) {
    return
  }

  const diagnostics = []
  if (missingFromFrontend.length > 0) {
    diagnostics.push('missing=' + missingFromFrontend.join(','))
  }
  if (unexpectedManagedIds.length > 0) {
    diagnostics.push('unexpected=' + unexpectedManagedIds.join(','))
  }

  throw new Error('[permission-contract] Frontend/backend permission drift detected: ' + diagnostics.join(' | '))
}
`

writeFileSync(outputFile, output)
