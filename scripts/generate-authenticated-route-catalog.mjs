import { readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, relative, resolve } from 'node:path'
import { collectAuthenticatedRoutePaths } from './authenticated-route-path-utils.mjs'

const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)))
const authenticatedRoutesDir = join(repoRoot, 'src', 'routes', '_authenticated')
const outputFile = join(
  repoRoot,
  'src',
  'features',
  'authz',
  'data',
  'authenticated-route-catalog.ts',
)

const routePaths = collectAuthenticatedRoutePaths(authenticatedRoutesDir)

const output = `// This file is auto-generated by scripts/generate-authenticated-route-catalog.mjs
// Do not edit manually.

export const AUTHENTICATED_ROUTE_PATHS = ${JSON.stringify(
  routePaths,
  null,
  2,
)} as const
`

writeFileSync(outputFile, output)
