import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  collectAuthenticatedRoutePaths,
  normalizePath,
} from './authenticated-route-path-utils.mjs'

const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)))
const authenticatedRoutesDir = resolve(repoRoot, 'src', 'routes', '_authenticated')
const outputFile = resolve(
  repoRoot,
  'server',
  'authz',
  'route_permission_contract.gen.go'
)
const hiddenPagePaths = new Set(['/', '/dashboard'])

function buildPermissionId(kind, routePath) {
  const normalizedPath = normalizePath(routePath)
  if (kind === 'page' && normalizedPath === '/') {
    return 'page_dashboard_home'
  }

  const suffix = normalizedPath
    .split('/')
    .filter(Boolean)
    .join('_')
    .toLowerCase()
    .replace(/[^a-z0-9_]/g, '_')

  return `${kind}_${suffix || 'root'}`
}

const permissionIds = collectAuthenticatedRoutePaths(authenticatedRoutesDir)
  .flatMap((routePath) => {
    const normalizedPath = normalizePath(routePath)
    const segmentCount = normalizedPath.split('/').filter(Boolean).length
    if (segmentCount <= 1) {
      return hiddenPagePaths.has(normalizedPath)
        ? []
        : [buildPermissionId('page', normalizedPath)]
    }
    return [buildPermissionId('tab', normalizedPath)]
  })
  .filter((permissionId, index, values) => values.indexOf(permissionId) === index)
  .sort()

const entries = permissionIds
  .map((permissionId) => `\t"${permissionId}": {},`)
  .join('\n')

const output = `// Code generated by scripts/generate-route-permission-contract.mjs; DO NOT EDIT.

package authz

var KnownRoutePermissionIDs = map[string]struct{}{
${entries}
}
`

writeFileSync(outputFile, output)
console.log(
  `[route-permission-contract] wrote ${permissionIds.length} route permission ids`
)
