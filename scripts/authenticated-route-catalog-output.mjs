import { join } from 'node:path'
import { collectAuthenticatedRoutePaths } from './authenticated-route-path-utils.mjs'

export function getAuthenticatedRouteCatalogFile(repoRoot) {
  return join(
    repoRoot,
    'src',
    'features',
    'authz',
    'data',
    'authenticated-route-catalog.ts',
  )
}

export function getAuthenticatedRoutesDirectory(repoRoot) {
  return join(repoRoot, 'src', 'routes', '_authenticated')
}

export function buildAuthenticatedRouteCatalogSource(repoRoot) {
  const routePaths = collectAuthenticatedRoutePaths(
    getAuthenticatedRoutesDirectory(repoRoot),
  )
  const routePathEntries = routePaths.map((path) => `  '${path}',`).join('\n')

  return `// This file is auto-generated by scripts/generate-authenticated-route-catalog.mjs
// Do not edit manually.

export const AUTHENTICATED_ROUTE_PATHS = [
${routePathEntries}
] as const
`
}
